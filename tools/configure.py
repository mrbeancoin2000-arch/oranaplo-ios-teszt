#!/usr/bin/env python3
"""Generate app config from an iOS OAuth client ID, never silently use demo mode.

The Google iOS OAuth Client ID is public; this tool never accepts a client secret,
access token or refresh token.
"""
from pathlib import Path
import json
import plistlib
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / 'google_oauth.json'


def validate_config(data):
    if not isinstance(data, dict):
        raise ValueError('A konfiguracionak JSON objektumnak kell lennie.')
    client = str(data.get('ios_client_id', '')).strip()
    bundle = str(data.get('ios_bundle_id', '')).strip()
    if not client or client.startswith('ADD_') or not re.fullmatch(r'[A-Za-z0-9_-]+\.apps\.googleusercontent\.com', client):
        raise ValueError('A google_oauth.json ios_client_id mezoje nem ervenyes iOS OAuth Client ID.')
    if not re.fullmatch(r'[A-Za-z][A-Za-z0-9-]*(?:\.[A-Za-z0-9-]+)+', bundle):
        raise ValueError('A google_oauth.json ios_bundle_id mezoje hianyzik vagy hibas.')
    return client, bundle


def main():
    if not CONFIG.is_file():
        print('HIBA: google_oauth.json hianyzik!')
        print('A build NEM indulhat demo OAuth beallitassal.')
        print('Allitsd vissza a korabban mukodo google_oauth.json fajlt, vagy keszitsd el a google_oauth.example.json alapjan.')
        print('Ne az Google client secretet add meg, csak az iOS Client ID-t es Bundle ID-t.')
        return 3
    try:
        data = json.loads(CONFIG.read_text(encoding='utf-8-sig'))
        client, bundle_id = validate_config(data)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print('HIBA: Google OAuth konfiguracio:', exc)
        print('Ne indits uj IPA buildet, amig nincs javitva a google_oauth.json.')
        return 3

    reversed_client = '.'.join(reversed(client.split('.')))
    swift = ROOT / 'ios/Sources/AppConfig.swift'
    swift.write_text('// Automatically generated by tools/configure.py; public OAuth client ID (not secret).\nimport Foundation\nenum AppConfig {\n    static let googleBundleID = "__BUNDLE__"\n    static let googleClientID = "__CLIENT__"\n}\n'.replace('__BUNDLE__', bundle_id).replace('__CLIENT__', client),encoding='utf-8')
    plist = ROOT / 'ios/Resources/Info.plist'
    info = plistlib.loads(plist.read_bytes()) if plist.exists() else {}
    # Keep the active-running background location mode. Earlier versions
    # reset UIBackgroundModes to ['fetch'] on every Windows setup.
    # Deduplicate safely and preserve any other declared modes.
    background = info.get('UIBackgroundModes', [])
    if not isinstance(background, list):
        background = []
    background = list(dict.fromkeys(
        [mode for mode in background if isinstance(mode, str)] + ['fetch', 'location']
    ))
    info.update({
        'CFBundleDevelopmentRegion': 'en',
        'CFBundleDisplayName': 'ÓraNapló',
        'CFBundleIdentifier': '$(PRODUCT_BUNDLE_IDENTIFIER)',
        'CFBundleExecutable': '$(EXECUTABLE_NAME)',
        'CFBundleName': '$(PRODUCT_NAME)',
        'CFBundlePackageType': 'APPL',
        'GIDClientID': client,
        'NSHealthShareUsageDescription': info.get('NSHealthShareUsageDescription') or 'Az ÓraNapló a jóváhagyott egészségadatokat helyben jeleníti meg, és a kiválasztott adatokat saját Google Sheets-fájlodba menti. A profil továbbítása külön jóváhagyást igényel.',
        'NSHealthUpdateUsageDescription': 'Az alkalmazas nem ir Apple Egeszseg-adatokat; csak olvasi engedelyt ker.',
        'CFBundleURLTypes': [{'CFBundleURLSchemes': [reversed_client]}],
        'BGTaskSchedulerPermittedIdentifiers': ['hu.oranaplo.ios.refresh'],
        'UIBackgroundModes': background,
        'UILaunchScreen': {},
        'UIRequiredDeviceCapabilities': ['arm64'],
        'UISupportedInterfaceOrientations': ['UIInterfaceOrientationPortrait'],
    })
    plist.write_bytes(plistlib.dumps(info, sort_keys=True))
    print('OK: Google iOS Client ID es Bundle ID beallitva.')
    print('OK: Google visszairanyitasi URL sema:', reversed_client)
    print('Google OAuth-hoz elvart Sideloadly utani Bundle ID:', bundle_id)
    print('FIGYELEM: Sideloadly telepites utan az alkalmazas Bundle ID-ja valtozhat; akkor az OAuth klienst is illeszteni kell.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
