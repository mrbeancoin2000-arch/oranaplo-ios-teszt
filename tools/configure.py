#!/usr/bin/env python3
"""Generate source-safe public OAuth ID constants + redirect plist. Never expects an OAuth client secret."""
from pathlib import Path
import json, plistlib, re, sys
ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / 'google_oauth.json'
if CONFIG.exists():
    info = json.loads(CONFIG.read_text(encoding='utf-8'))
else:
    info = {'ios_client_id': 'ADD_GOOGLE_IOS_CLIENT_ID.apps.googleusercontent.com'}
client = info.get('ios_client_id','').strip()
if not re.fullmatch(r'[A-Za-z0-9_.-]+\.apps\.googleusercontent\.com', client):
    print('HIBA: a google_oauth.json ios_client_id mezője hibás!')
    sys.exit(2)
rev = 'hu.oranaplo.demo' if client.startswith('ADD_') else '.'.join(reversed(client.split('.')))
source = ROOT/'ios/Sources/AppConfig.swift'
source.write_text('''// Automatically generated by tools/configure.py; OAuth client ID is PUBLIC, never a secret.\nimport Foundation\nenum AppConfig {\n    static let googleClientID = "'''+client+'''"\n}\n''', encoding='utf-8')
info_plist = {
  'CFBundleDevelopmentRegion':'hu', 'CFBundleDisplayName':'ÓraNapló',
  'CFBundleIdentifier':'$(PRODUCT_BUNDLE_IDENTIFIER)', 'CFBundleExecutable':'$(EXECUTABLE_NAME)',
  'CFBundleName':'$(PRODUCT_NAME)', 'CFBundlePackageType':'APPL',
  'CFBundleShortVersionString':'0.3.0', 'CFBundleVersion':'3',
  'LSRequiresIPhoneOS': True,
  'NSHealthShareUsageDescription':'A kért egészségadatokat a saját Google Sheets-fájljába mentjük; nem küldjük azokat az ÓraNapló szervereire.',
  'NSHealthUpdateUsageDescription':'Az alkalmazás nem ír egészségadatot. Kizárólag olvasási jogosultságot kér.',
  'BGTaskSchedulerPermittedIdentifiers':['hu.oranaplo.ios.refresh'],
  'UIBackgroundModes':['fetch'],
  'CFBundleURLTypes':[{'CFBundleURLSchemes':[rev]}],
  'UILaunchScreen': {},
  'UIRequiredDeviceCapabilities':['arm64'],
  'UISupportedInterfaceOrientations':['UIInterfaceOrientationPortrait']
}
with (ROOT/'ios/Resources/Info.plist').open('wb') as f: plistlib.dump(info_plist,f, sort_keys=True)
print('Google kliensazonosító konfigurálva.' if not client.startswith('ADD_') else 'Demó konfiguráció: Google bejelentkezéshez töltsd ki a google_oauth.json fájlt!')
print('URL-séma:',rev)
